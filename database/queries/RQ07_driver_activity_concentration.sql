/*
   CMPG321 - Phase 2 - RQ07
   Driver Platform Affiliation & Activity Concentration

   Research question:
   How are completed trips and total driver payouts distributed among
   drivers across platform affiliations, and what proportion of total
   driver earnings is generated by the top 10% most active drivers
   within each platform?

   Definitions and interpretation:
   - Include only TRIP_HEADERS.trip_status = 'COMPLETED'.
   - An active driver has at least one observed completed trip. Do not use
     SA_DRIVERS.total_lifetime_trips to rank activity in this dataset.
   - Rank separately by affiliation_id: completed trips descending, then
     driver_id ascending. ROW_NUMBER selects exactly CEIL(0.10 * N)
     drivers, even when activity ties cross the cutoff. For small groups
     the selected cohort can exceed 10% of active drivers.
   - Uber and Bolt mean exclusive driver affiliations. Dual-Platform (Both)
     is a separate group; there is no trip-level platform identifier with
     which to split its trips or payouts between Uber and Bolt.
   - Use recorded driver_payout_zar, without deducting commission again.
     These are payouts, not profit after fuel, maintenance or other costs.
   - Count completed headers even if a fare row is absent. Payout totals
     sum known amounts (NVL supplies zero only for aggregation), while
     trips_without_payout exposes absent fares or NULL payout values.
     Payout percentages and averages are NULL if their denominator group
     has any unknown payouts; NULLIF also returns NULL for zero totals.
   - Query A includes every affiliation, including those with no activity.
     Query B includes active drivers only. Percentages are rounded to two
     decimals only at presentation; rounded shares may not sum to 100.

   Join safety and execution:
   TRIP_HEADERS.trip_id and TRIP_FARE_BREAKDOWN.trip_id are primary keys,
   so their join contributes at most one fare row per trip. Aggregate to
   one row per driver before joining SA_DRIVERS and PLATFORM_AFFILIATION
   through their primary/foreign keys. No reviews or vehicles are needed.
   Keep the declared PK/FK constraints enabled; do not mask bad joins with
   DISTINCT. Each statement scans completed trips and sorts driver totals
   for analytic ranking. Run both SELECT statements as CMPG321 (F5 in SQL
   Developer). The repeated CTEs let each query run independently without
   creating views, temporary tables or other database objects.

   Local CSV audit (2026-10-13; Oracle execution still required):
   33,331 completed trips; 800 active drivers; total payout 12,116,653.04 ZAR.
   Uber: 280 active, top 28 payout share 13.45%.
   Bolt: 261 active, top 27 payout share 13.53%.
   Dual-Platform (Both): 259 active, top 26 payout share 12.80%.
   These are expected results for the supplied CSVs, not a live DB claim.
*/


/*
   QUERY A: AFFILIATION SUMMARY AND TOP-10% CONCENTRATION

   all_*_share_pct uses totals across all affiliations as the denominator.
   top_10pct_*_share_pct uses that affiliation's own total.
*/
WITH completed_driver_activity AS (
    SELECT
        h.driver_id,
        COUNT(*) AS completed_trips,
        SUM(NVL(f.driver_payout_zar, 0)) AS total_driver_payout_zar,
        COUNT(*) - COUNT(f.driver_payout_zar) AS trips_without_payout
    FROM TRIP_HEADERS h
    LEFT JOIN TRIP_FARE_BREAKDOWN f
        ON f.trip_id = h.trip_id
    WHERE h.trip_status = 'COMPLETED'
    GROUP BY h.driver_id
),
ranked_drivers AS (
    SELECT
        d.affiliation_id,
        a.driver_id,
        a.completed_trips,
        a.total_driver_payout_zar,
        a.trips_without_payout,
        ROW_NUMBER() OVER (
            PARTITION BY d.affiliation_id
            ORDER BY a.completed_trips DESC, a.driver_id ASC
        ) AS activity_rank,
        COUNT(*) OVER (
            PARTITION BY d.affiliation_id
        ) AS active_drivers_in_platform
    FROM completed_driver_activity a
    JOIN SA_DRIVERS d
        ON d.driver_id = a.driver_id
),
platform_totals AS (
    SELECT
        affiliation_id,
        COUNT(*) AS active_drivers,
        SUM(completed_trips) AS completed_trips,
        SUM(total_driver_payout_zar) AS total_payout_zar,
        SUM(trips_without_payout) AS trips_without_payout,
        SUM(
            CASE
                WHEN activity_rank <= CEIL(0.10 * active_drivers_in_platform)
                THEN completed_trips
                ELSE 0
            END
        ) AS top_10pct_completed_trips,
        SUM(
            CASE
                WHEN activity_rank <= CEIL(0.10 * active_drivers_in_platform)
                THEN total_driver_payout_zar
                ELSE 0
            END
        ) AS top_10pct_payout_zar
    FROM ranked_drivers
    GROUP BY affiliation_id
)
SELECT
    pa.affiliation_name AS platform_affiliation,
    NVL(pt.active_drivers, 0) AS active_drivers,
    NVL(pt.completed_trips, 0) AS completed_trips,
    ROUND(
        100 * NVL(pt.completed_trips, 0)
        / NULLIF(SUM(NVL(pt.completed_trips, 0)) OVER (), 0),
        2
    ) AS all_trip_share_pct,
    ROUND(NVL(pt.total_payout_zar, 0), 2) AS total_payout_zar,
    CASE
        WHEN SUM(NVL(pt.trips_without_payout, 0)) OVER () = 0
        THEN ROUND(
            100 * NVL(pt.total_payout_zar, 0)
            / NULLIF(SUM(NVL(pt.total_payout_zar, 0)) OVER (), 0),
            2
        )
    END AS all_payout_share_pct,
    ROUND(
        pt.completed_trips / NULLIF(pt.active_drivers, 0), 2
    ) AS avg_trips_per_driver,
    CASE
        WHEN NVL(pt.trips_without_payout, 0) = 0
        THEN ROUND(
            pt.total_payout_zar / NULLIF(pt.active_drivers, 0), 2
        )
    END AS avg_payout_per_driver_zar,
    CEIL(0.10 * NVL(pt.active_drivers, 0)) AS top_10pct_drivers,
    ROUND(
        100 * CEIL(0.10 * NVL(pt.active_drivers, 0))
        / NULLIF(pt.active_drivers, 0),
        2
    ) AS top_10pct_driver_share_pct,
    NVL(pt.top_10pct_completed_trips, 0) AS top_10pct_completed_trips,
    ROUND(
        100 * pt.top_10pct_completed_trips
        / NULLIF(pt.completed_trips, 0),
        2
    ) AS top_10pct_trip_share_pct,
    ROUND(NVL(pt.top_10pct_payout_zar, 0), 2) AS top_10pct_payout_zar,
    CASE
        WHEN NVL(pt.trips_without_payout, 0) = 0
        THEN ROUND(
            100 * pt.top_10pct_payout_zar
            / NULLIF(pt.total_payout_zar, 0),
            2
        )
    END AS top_10pct_payout_share_pct,
    NVL(pt.trips_without_payout, 0) AS trips_without_payout
FROM PLATFORM_AFFILIATION pa
LEFT JOIN platform_totals pt
    ON pt.affiliation_id = pa.affiliation_id
ORDER BY pa.affiliation_name;


/*
   QUERY B: INDIVIDUAL DRIVER DISTRIBUTION

   One row per active driver. Shares use that driver's affiliation totals.
   top_10pct_member uses exactly the same ranking and cutoff as Query A;
   summing its YES rows reproduces Query A's top-cohort totals.
*/
WITH completed_driver_activity AS (
    SELECT
        h.driver_id,
        COUNT(*) AS completed_trips,
        SUM(NVL(f.driver_payout_zar, 0)) AS total_driver_payout_zar,
        COUNT(*) - COUNT(f.driver_payout_zar) AS trips_without_payout
    FROM TRIP_HEADERS h
    LEFT JOIN TRIP_FARE_BREAKDOWN f
        ON f.trip_id = h.trip_id
    WHERE h.trip_status = 'COMPLETED'
    GROUP BY h.driver_id
),
ranked_drivers AS (
    SELECT
        d.affiliation_id,
        a.driver_id,
        a.completed_trips,
        a.total_driver_payout_zar,
        a.trips_without_payout,
        ROW_NUMBER() OVER (
            PARTITION BY d.affiliation_id
            ORDER BY a.completed_trips DESC, a.driver_id ASC
        ) AS activity_rank,
        COUNT(*) OVER (
            PARTITION BY d.affiliation_id
        ) AS active_drivers_in_platform,
        SUM(a.completed_trips) OVER (
            PARTITION BY d.affiliation_id
        ) AS platform_completed_trips,
        SUM(a.total_driver_payout_zar) OVER (
            PARTITION BY d.affiliation_id
        ) AS platform_payout_zar,
        SUM(a.trips_without_payout) OVER (
            PARTITION BY d.affiliation_id
        ) AS platform_missing_payouts
    FROM completed_driver_activity a
    JOIN SA_DRIVERS d
        ON d.driver_id = a.driver_id
)
SELECT
    pa.affiliation_name AS platform_affiliation,
    r.driver_id,
    r.activity_rank,
    r.completed_trips,
    ROUND(r.total_driver_payout_zar, 2) AS total_driver_payout_zar,
    ROUND(
        100 * r.completed_trips / NULLIF(r.platform_completed_trips, 0), 2
    ) AS platform_trip_share_pct,
    CASE
        WHEN r.platform_missing_payouts = 0
        THEN ROUND(
            100 * r.total_driver_payout_zar
            / NULLIF(r.platform_payout_zar, 0),
            2
        )
    END AS platform_payout_share_pct,
    CASE
        WHEN r.activity_rank <= CEIL(0.10 * r.active_drivers_in_platform)
        THEN 'YES'
        ELSE 'NO'
    END AS top_10pct_member,
    r.trips_without_payout
FROM ranked_drivers r
JOIN PLATFORM_AFFILIATION pa
    ON pa.affiliation_id = r.affiliation_id
ORDER BY pa.affiliation_name, r.activity_rank;
